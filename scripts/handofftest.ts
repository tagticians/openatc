import { setAirport } from '../src/data/airport';
import { AIRPORTS } from '../src/data/registry';
setAirport(AIRPORTS[0]);
import { Sim } from '../src/sim/sim';
import { execute } from '../src/sim/commands';
const sim = new Sim();
sim.settings.arrivalsPerHour = 0; sim.settings.departuresPerHour = 0;
sim.start();
const d = sim.aircraft.find((a) => a.kind === 'dep' && a.phase === 'ready')!;
sim.selectedId = d.id;
console.log(execute(sim, 'CTO').error ?? 'CTO ok');
for (let i = 0; i < 4 * 150; i++) sim['step'](0.25);
console.log('before HO', Math.round(d.alt), 'cfl', d.cfl);
console.log(execute(sim, 'HO').error ?? 'HO ok');
for (let i = 0; i < 4 * 120; i++) sim['step'](0.25);
console.log('2 min after HO', Math.round(d.alt), 'cfl', d.cfl, 'phase', d.phase);
console.log(sim.radio.filter((m) => m.callsign === d.callsign).map((m) => `${m.from}: ${m.text}`).join('\n'));
const after = execute(sim, `${d.callsign} C90`);
console.log('command after hand-off:', after.ok ? 'ACCEPTED (bug)' : `refused: ${after.error}`);
